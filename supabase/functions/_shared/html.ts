/** Encode plain text at the HTML output boundary, never when saving form data.
 * This is for text nodes and quoted attributes, not URLs, CSS or JavaScript.
 */
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;')
}
